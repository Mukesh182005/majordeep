#!/usr/bin/env python3
"""Aggregate the ASVspoof 2019 LA eval results of the selected seeds.

Reads ``paper/config/audio_model_selection.json`` and, for each selected
checkpoint, the eval score file and metrics written by
``ml/evaluation/eval_asvspoof.py``. Writes, without running any model:

* ``paper_results/audio_asvspoof2019la/metrics.json``: per-seed and mean/SD
  pooled EER, min t-DCF, AUC, and the per-attack EER table;
* ``paper_results/audio_asvspoof2019la/config.json``: inputs with sha256 and
  provenance;
* ``paper/tables/audio_asvspoof_pooled.tex`` and ``audio_asvspoof_per_attack.tex``;
* ``paper/figures/audio_asvspoof_det.pdf`` (and ``.png``);
* the ``audio_asvspoof2019la`` section of ``paper_results/INDEX.md``.

Usage::

    python paper/analysis/audio_asvspoof_report.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from ml.common import REPO_ROOT  # noqa: E402

RESULTS = REPO_ROOT / "paper_results/audio_asvspoof2019la"
SELECTION_FILE = REPO_ROOT / "paper/config/audio_model_selection.json"
TABLES = REPO_ROOT / "paper/tables"
FIGURES = REPO_ROOT / "paper/figures"
EVAL_ATTACKS = [f"A{i:02d}" for i in range(7, 20)]


def mean_sd(values: list[float]) -> dict:
    array = np.asarray(values, dtype=np.float64)
    return {
        "mean": float(array.mean()),
        "sd": float(array.std(ddof=1)) if array.size > 1 else 0.0,
        "n": int(array.size),
        "values": [float(v) for v in array],
    }


def aggregate(per_seed: list[dict]) -> dict:
    """Mean and sample SD over seeds of every metric in the per-seed records."""
    summary = {
        "eer_percent": mean_sd([m["eer"] * 100 for m in per_seed]),
        "auc_bonafide_vs_spoof": mean_sd([m["auc_bonafide_vs_spoof"] for m in per_seed]),
        "min_tdcf": None,
        "per_attack_eer_percent": {},
    }
    if all(m.get("min_tdcf") is not None for m in per_seed):
        summary["min_tdcf"] = mean_sd([m["min_tdcf"] for m in per_seed])
    attacks = sorted(set.intersection(*(set(m["per_attack"]) for m in per_seed)))
    for attack in attacks:
        summary["per_attack_eer_percent"][attack] = mean_sd([m["per_attack"][attack]["eer"] * 100 for m in per_seed])
    return summary


def _pm(entry: dict, digits: int) -> str:
    return f"{entry['mean']:.{digits}f} $\\pm$ {entry['sd']:.{digits}f}"


def write_tables(summary: dict, frontend: str, baselines: dict) -> list[Path]:
    TABLES.mkdir(parents=True, exist_ok=True)
    tdcf = _pm(summary["min_tdcf"], 4) if summary["min_tdcf"] else "--"
    pooled = TABLES / "audio_asvspoof_pooled.tex"
    pooled.write_text(
        "% Generated by paper/analysis/audio_asvspoof_report.py -- do not edit.\n"
        "\\begin{tabular}{lcc}\n\\hline\n"
        "System & min t-DCF & EER (\\%) \\\\\n\\hline\n"
        f"B01 CQCC-GMM \\cite{{todisco2019asvspoof}} & {baselines['B01_CQCC_GMM']['min_tdcf']:.4f} & "
        f"{baselines['B01_CQCC_GMM']['eer_percent']:.2f} \\\\\n"
        f"B02 LFCC-GMM \\cite{{todisco2019asvspoof}} & {baselines['B02_LFCC_GMM']['min_tdcf']:.4f} & "
        f"{baselines['B02_LFCC_GMM']['eer_percent']:.2f} \\\\\n"
        f"LCNN, {frontend} (ours, {summary['eer_percent']['n']} seeds) & {tdcf} & {_pm(summary['eer_percent'], 2)} \\\\\n"
        "\\hline\n\\end{tabular}\n",
        encoding="utf-8",
    )
    per_attack = TABLES / "audio_asvspoof_per_attack.tex"
    rows = "".join(
        f"{attack} & {_pm(entry, 2)} \\\\\n" for attack, entry in summary["per_attack_eer_percent"].items()
    )
    per_attack.write_text(
        "% Generated by paper/analysis/audio_asvspoof_report.py -- do not edit.\n"
        "\\begin{tabular}{lc}\n\\hline\nAttack & EER (\\%) \\\\\n\\hline\n" + rows + "\\hline\n\\end{tabular}\n",
        encoding="utf-8",
    )
    return [pooled, per_attack]


def write_det_figure(score_files: list[tuple[int, Path]]) -> list[Path]:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from scipy.stats import norm

    from ml.evaluation.asvspoof_metrics import det_curve
    from ml.evaluation.eval_asvspoof import read_scores

    FIGURES.mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(figsize=(3.4, 3.2))
    ticks = np.array([0.1, 0.5, 1, 2, 5, 10, 20, 40]) / 100
    for seed, path in score_files:
        data = read_scores(path)
        p_miss, p_fa, _ = det_curve(data["score"][data["label"] == 0], data["score"][data["label"] == 1])
        clip = np.clip
        ax.plot(norm.ppf(clip(p_fa, 1e-4, 1 - 1e-4)), norm.ppf(clip(p_miss, 1e-4, 1 - 1e-4)), lw=1, label=f"seed {seed}")
    ax.set_xticks(norm.ppf(ticks), [f"{t * 100:g}" for t in ticks])
    ax.set_yticks(norm.ppf(ticks), [f"{t * 100:g}" for t in ticks])
    ax.set_xlim(norm.ppf(0.0005), norm.ppf(0.5))
    ax.set_ylim(norm.ppf(0.0005), norm.ppf(0.5))
    ax.set_xlabel("False alarm rate (%)")
    ax.set_ylabel("Miss rate (%)")
    ax.grid(True, lw=0.3)
    ax.legend(fontsize=7)
    fig.tight_layout()
    outputs = [FIGURES / "audio_asvspoof_det.pdf", FIGURES / "audio_asvspoof_det.png"]
    for out in outputs:
        fig.savefig(out, dpi=200)
    plt.close(fig)
    return outputs


def main() -> int:
    from ml.preprocessing.build_asvspoof2019_la import sha256_file
    from ml.provenance import collect_provenance
    from paper.analysis.index_tools import update_index_section

    if not SELECTION_FILE.is_file():
        raise SystemExit("No dev-based selection yet (paper/config/audio_model_selection.json).")
    selection = json.loads(SELECTION_FILE.read_text(encoding="utf-8"))
    frontend = selection["selected_frontend"]

    per_seed, inputs, score_files = [], {}, []
    for entry in selection["selected_checkpoints"]:
        stem = Path(entry["checkpoint"]).stem
        metrics_path = RESULTS / "eval" / f"{stem}_eval_metrics.json"
        scores_path = RESULTS / "eval" / f"{stem}_eval_scores.csv"
        if not metrics_path.is_file() or not scores_path.is_file():
            raise SystemExit(f"Missing eval results for {stem}; score it with eval_asvspoof.py first.")
        metrics = json.loads(metrics_path.read_text(encoding="utf-8"))
        if metrics["checkpoint_sha256"] != entry["sha256"]:
            raise SystemExit(f"{metrics_path.name} was not produced by the selected checkpoint.")
        per_seed.append({**metrics, "seed": entry["seed"]})
        score_files.append((entry["seed"], scores_path))
        for path in (metrics_path, scores_path):
            inputs[path.relative_to(REPO_ROOT).as_posix()] = sha256_file(path)

    summary = aggregate(per_seed)
    baselines = json.loads((RESULTS / "baselines.json").read_text(encoding="utf-8"))
    result = {
        "dataset": "ASVspoof 2019 LA, official eval partition (attacks A07-A19)",
        "frontend": frontend,
        "seeds": [m["seed"] for m in per_seed],
        "summary": summary,
        "per_seed": [
            {
                "seed": m["seed"],
                "eer_percent": m["eer"] * 100,
                "min_tdcf": m.get("min_tdcf"),
                "auc_bonafide_vs_spoof": m["auc_bonafide_vs_spoof"],
                "per_attack_eer_percent": {a: v["eer"] * 100 for a, v in m["per_attack"].items()},
                "per_attack_min_tdcf": {a: v.get("min_tdcf") for a, v in m["per_attack"].items()},
            }
            for m in per_seed
        ],
    }
    (RESULTS / "metrics.json").write_text(json.dumps(result, indent=2), encoding="utf-8")
    written = write_tables(summary, frontend, baselines["eval"]) + write_det_figure(score_files)
    (RESULTS / "config.json").write_text(
        json.dumps(
            {
                "inputs_sha256": inputs,
                "selection_file": SELECTION_FILE.relative_to(REPO_ROOT).as_posix(),
                "outputs": [p.relative_to(REPO_ROOT).as_posix() for p in written],
                "sd": "sample standard deviation over seeds (ddof=1)",
                "provenance": collect_provenance(seeds=result["seeds"]),
            },
            indent=2,
            default=str,
        ),
        encoding="utf-8",
    )

    file = "paper_results/audio_asvspoof2019la/metrics.json"
    rows = [
        ("Audio LA eval EER, mean (%)", f"{summary['eer_percent']['mean']:.2f}", file, "summary.eer_percent.mean", "2"),
        ("Audio LA eval EER, SD (%)", f"{summary['eer_percent']['sd']:.2f}", file, "summary.eer_percent.sd", "2"),
        ("Audio LA eval AUC, mean", f"{summary['auc_bonafide_vs_spoof']['mean']:.4f}", file,
         "summary.auc_bonafide_vs_spoof.mean", "2"),
    ]
    if summary["min_tdcf"]:
        rows += [
            ("Audio LA eval min t-DCF, mean", f"{summary['min_tdcf']['mean']:.4f}", file, "summary.min_tdcf.mean", "2"),
            ("Audio LA eval min t-DCF, SD", f"{summary['min_tdcf']['sd']:.4f}", file, "summary.min_tdcf.sd", "2"),
        ]
    rows += [
        (f"Audio LA eval EER {attack}, mean (%)", f"{entry['mean']:.2f}", file,
         f"summary.per_attack_eer_percent.{attack}.mean", "2")
        for attack, entry in summary["per_attack_eer_percent"].items()
    ]
    rows += [
        ("Baseline B01 CQCC-GMM eval EER (%) [published]", f"{baselines['eval']['B01_CQCC_GMM']['eer_percent']:.2f}",
         "paper_results/audio_asvspoof2019la/baselines.json", "eval.B01_CQCC_GMM.eer_percent", "2"),
        ("Baseline B02 LFCC-GMM eval EER (%) [published]", f"{baselines['eval']['B02_LFCC_GMM']['eer_percent']:.2f}",
         "paper_results/audio_asvspoof2019la/baselines.json", "eval.B02_LFCC_GMM.eer_percent", "2"),
    ]
    update_index_section("audio_asvspoof2019la", rows)
    print(json.dumps(summary, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
